#pragma pack(push, 1)
struct D2NpcGossipLineStrc {
    uint16_t wStringId;           // +0x00 (.tbl string ID)
    uint8_t  bRequireQuestDone;   // +0x02
    int32_t  bBeforeQuestOrAvail; // +0x03
    int32_t  nQuestFilterId;      // +0x07
    int32_t  nCharClassFilter;    // +0x0B (0..6 = class, 7 = any class)
};
static_assert(sizeof(D2NpcGossipLineStrc) == 15, "D2NpcGossipLineStrc must be 15 bytes");

struct D2NpcGossipDefStrc {
    uint32_t                   dwNpcClassId;   // +0x00
    uint8_t                    nAct;           // +0x04
    const D2NpcGossipLineStrc* pLines;         // +0x05
    uint32_t                   nLineCount;     // +0x09
    uint32_t                   dwLastPicked;   // +0x0D
    uint16_t                   wUnk11;         // +0x11
    uint8_t                    bSkipAutoIntro; // +0x13
    uint8_t                    bIntroShown;    // +0x14
    uint8_t                    bHasGossip;     // +0x15
};
static_assert(sizeof(D2NpcGossipDefStrc) == 22, "D2NpcGossipDefStrc must be 22 bytes");

struct D2NpcQuestTopicMapStrc {
    uint16_t wSpeechStringId;     // +0x00
    uint16_t wTopicTitleStringId; // +0x02
};
#pragma pack(pop)

